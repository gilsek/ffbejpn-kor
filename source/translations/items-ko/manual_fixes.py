def main():
    m = C.read(C.HERE/'manifest.json')
    result = C.read(C.HERE/'manual_fixes.json') if (C.HERE/'manual_fixes.json').exists() else {}
    known = C.N.name_sources()[0]
    for path in sorted((C.ROOT/'translations/names-ko').glob('names_pass[0-9].json')):
        for jp,ko in C.read(path).items(): known.setdefault(jp,ko)
    composed = 0
    for rec in m['records']:
        source,rid = rec['source'],rec['ffbe_id']
        stat = re.fullmatch(r'(HP|MP)アップ:(\d+)%',source)
        if stat:
            result[rid] = f'{stat[1]} {stat[2]}% 증가'
        if rec['category'] == 'F_RECIPE_MST' and C.TAG.search(source):
            parts = re.split(r'(<[^>]+>)',source)
            if all(not C.JP.search(p) or p.strip() in known for p in parts if not C.TAG.fullmatch(p)):
                result[rid] = ''.join(p.replace(p.strip(),known[p.strip()])
                                      if C.JP.search(p) and not C.TAG.fullmatch(p) else p for p in parts)
                composed += 1
        if source in FIXES: result[rid] = FIXES[source]
        if rid in m['reused'] and re.search(r'\+[1-4]$',source):
            ko = m['reused'][rid]
            if re.search(r' [IV]+$',ko):
                result[rid] = re.sub(r' [IV]+$','',ko)+re.search(r'\+[1-4]$',source).group()
    result.update(ID_FIXES)
    (C.HERE/'manual_fixes.json').write_text(json.dumps(result,ensure_ascii=False,indent=1)+'\n',encoding='utf-8')
    print('명칭·본문 보정',len(result),'개, 기존 지명/상점명 조합',composed,'개')


if __name__ == '__main__': main()
