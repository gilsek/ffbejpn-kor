#!/usr/bin/env python3
"""일본판 팩에 없는 던전/구역 배너 아이콘 이름 -> 대신 쓸 일본판 배너 이름 표(Frida용 JS)를 만든다.

왜: GateDungeonScene 던전 목록은 칸마다 IconMstList::getFileName(DungeonMst.iconId)로 배너를 읽는다.
F_ICON_MST의 spd_ 배너 1062개 중 766개는 기기 일판 spdungeon1..9.cpk TOC에 없다(영문판 추출본에만 있음).
그 이름은 getOrCreateSpriteBatchNode가 null을 돌려주고, jp_event_menu.js의 대비 처리가 common.png로 바꿔도
목록 전체가 빈 칸으로 그려진다(기기 2026-11-14, 711 기억의 회랑: JP_EVENT_ART_MISS "spd_bn_list_FFBE.png").
이 표는 빠진 이름마다 그 아이콘을 쓰는 구역의 배너(jp_event_art.json by_area, 일판 팩 파일)를 대신 준다.
구역 배너가 없으면 중립 판(jp_event_art.json neutral)을 준다.

출력: build/frida/jp_icon_fallback.js (globalThis.__jpIconFallback = {missing: replacement})
deploy_jp_frida.py가 jp_event_menu.js보다 먼저 붙인다.

usage: python -I -X utf8 build/make_jp_icon_fallback.py
"""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MST = ROOT / 'build/out/jp_offline/engine/static/mst_decoded'
TOC = ROOT / 'build/out/seal_room/banner_files.tsv'
ART = ROOT / 'build/engine_overlay/jp_event_art.json'
OUT = ROOT / 'build/frida/jp_icon_fallback.js'


def rows(name):
    with open(MST / name, encoding='utf-8') as fh:
        return [json.loads(line) for line in fh if line.strip()]


def main():
    with open(TOC, encoding='utf-8') as fh:
        shipped = {r['file'] for r in csv.DictReader(fh, delimiter='\t')}
    art = json.loads(ART.read_text(encoding='utf-8'))
    by_area, neutral = art.get('by_area') or {}, art.get('neutral') or 'spd_bn_list_dummy.png'
    assert neutral in shipped, neutral
    icons = {r['0HUPxDf1']: r['qtkvrS60'] for r in rows('F_ICON_MST.ndjson')}
    icon_areas = {}
    for r in rows('F_DUNGEON_MST.ndjson') + rows('F_AREA_MST.ndjson'):
        icon, area = str(r.get('0HUPxDf1') or ''), str(r.get('uv60hgDW') or '')
        if icon and area:
            icon_areas.setdefault(icon, []).append(area)
    table, stats = {}, {'area': 0, 'neutral': 0}
    for icon, name in sorted(icons.items(), key=lambda kv: int(kv[0]) if kv[0].isdigit() else 0):
        if not name.startswith('spd_') or name in shipped or name in table:
            continue
        pick = next((by_area[a] for a in icon_areas.get(icon, []) if by_area.get(a) in shipped), None)
        table[name] = pick or neutral
        stats['area' if pick else 'neutral'] += 1
    OUT.write_text(
        '// generated by build/make_jp_icon_fallback.py -- do not edit\n'
        '// JP-absent spd_ banner icon -> JP-shipped banner of the same area (or the neutral plate)\n'
        'globalThis.__jpIconFallback = ' + json.dumps(table, ensure_ascii=False, indent=0) + ';\n',
        encoding='utf-8')
    print('written %s: %d names (area banner %d, neutral %d)' % (OUT.name, len(table), stats['area'], stats['neutral']))
    for k in ('spd_bn_list_FFBE.png', 'spd_bn_list_FFV.png'):
        print('  ', k, '->', table.get(k))


if __name__ == '__main__':
    main()
